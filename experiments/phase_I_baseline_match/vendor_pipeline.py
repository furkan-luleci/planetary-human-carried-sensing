def segments(path, names):
    src = open(path).read()
    out = {}
    for node in ast.parse(src).body:
        nm = None
        if isinstance(node, ast.FunctionDef):
            nm = node.name
        elif isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            nm = node.targets[0].id
        if nm in names:
            out[nm] = (node.lineno, ast.get_source_segment(src, node))
    missing = [n for n in names if n not in out]
    if missing:
        raise SystemExit(f"not found in {path}: {missing}")
    return out


def config_values(path):
    src = open(path).read()
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == "CONFIG":
            call = node.value
            return {kw.arg: ast.literal_eval(kw.value) for kw in call.keywords if kw.arg in CONFIG_KEYS}
    raise SystemExit("CONFIG not found")


